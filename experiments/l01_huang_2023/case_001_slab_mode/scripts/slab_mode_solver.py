"""1D multilayer slab-waveguide mode solver (TE/TM), config-driven.

Pipeline: load_config -> solve_modes -> validate_result -> write_result.
All physical parameters come from the JSON config (params.json); nothing is
hard-coded here. Outputs a machine-readable result.json and a results.md.

Usage:
  python slab_mode_solver.py --config params.json [--output results/result.json]
"""

import argparse
import json
import os

import numpy as np


def load_config(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def _condition(neff, tm, k0, core, n_top, n_bot):
    M = np.eye(2, dtype=complex)
    for _, n, d in core:
        k = k0 * np.sqrt(n**2 - neff**2 + 0j)
        kk = k / (n**2) if tm else k
        m = np.array(
            [
                [np.cos(k * d), np.sin(k * d) / kk],
                [-kk * np.sin(k * d), np.cos(k * d)],
            ]
        )
        M = m @ M
    gt = k0 * np.sqrt(neff**2 - n_top**2 + 0j)
    gb = k0 * np.sqrt(neff**2 - n_bot**2 + 0j)
    gt_ = gt / (n_top**2) if tm else gt
    gb_ = gb / (n_bot**2) if tm else gb
    return M[1, 0] + M[1, 1] * gt_ + gb_ * (M[0, 0] + M[0, 1] * gt_)


def solve_modes(config, tm=True, npts=12000, bisect_iters=120, imag_tol=1e-3):
    """Return (roots, lambda0). Roots are guided-mode effective indices."""
    lambda0 = float(config["lambda0_um"])
    k0 = 2 * np.pi / lambda0
    stack = config["stack_top_to_bottom"]
    layers = [(item["name"], float(item["n"]), item.get("thickness_um")) for item in stack]
    if layers[0][2] is not None or layers[-1][2] is not None:
        raise ValueError("first and last layers must be semi-infinite (thickness_um = null)")
    n_top, n_bot = layers[0][1], layers[-1][1]
    core = layers[1:-1]
    if not core:
        raise ValueError("stack needs at least one finite core layer")

    nmin = max(n_top, n_bot) + 1e-6
    nmax = max(n for _, n, _ in core) - 1e-6
    xs = np.linspace(nmin, nmax, npts)
    roots = []
    prev_x, prev_f = xs[0], _condition(xs[0], tm, k0, core, n_top, n_bot)
    for x in xs[1:]:
        f = _condition(x, tm, k0, core, n_top, n_bot)
        if prev_f.real * f.real < 0 and abs(f.imag) < imag_tol:
            a, b, fa = prev_x, x, prev_f.real
            for _ in range(bisect_iters):
                mid = 0.5 * (a + b)
                fm = _condition(mid, tm, k0, core, n_top, n_bot).real
                if fa * fm <= 0:
                    b = mid
                else:
                    a, fa = mid, fm
            roots.append(0.5 * (a + b))
        prev_x, prev_f = x, f
    return roots, lambda0


def validate_result(modes_by_polarization, tolerance=0.01):
    """Basic sanity checks: each polarization finds at least one guided mode."""
    for name, roots in modes_by_polarization.items():
        if not roots:
            raise ValueError(f"no guided {name} mode found")
        if any(not (1.0 < neff < 2.5) for neff in roots):
            raise ValueError(f"{name} root outside physical range")
    return True


def build_result(config, modes_by_polarization, dispersion):
    lambda0 = float(config["lambda0_um"])
    modes = []
    for pol, roots in modes_by_polarization.items():
        for neff in roots:
            modes.append(
                {
                    "mode": pol,
                    "n_eff": round(float(neff), 4),
                    "lambda_guided_um": round(lambda0 / float(neff), 3),
                }
            )
    return {
        "lambda0_um": lambda0,
        "modes": modes,
        "dispersion_tm0": dispersion,
        "config_note": "generated by slab_mode_solver.py; results.md derived from this JSON",
    }


def write_result(result, output_path):
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as handle:
        json.dump(result, handle, indent=2, ensure_ascii=False)
    return output_path


def render_markdown(result):
    lines = ["# case_001 结果表（由 slab_mode_solver.py 自动生成）", ""]
    lines.append(f"## 导模（λ₀ = {result['lambda0_um']} μm，固定折射率）")
    lines.append("")
    lines.append("| 模式 | n_eff | λ_guided (μm) |")
    lines.append("| --- | --- | --- |")
    for mode in result["modes"]:
        lines.append(f"| {mode['mode']} | {mode['n_eff']} | {mode['lambda_guided_um']} |")
    lines.append("")
    if result.get("dispersion_tm0"):
        lines.append("## TM₀ 色散")
        lines.append("")
        lines.append("| λ₀ (μm) | n_eff (TM₀) |")
        lines.append("| --- | --- |")
        for item in result["dispersion_tm0"]:
            lines.append(f"| {item['lambda0']} | {item['n_eff_tm0']} |")
        lines.append("")
    lines.append("> 本文件由程序生成，勿手工编辑（评审要求：结果表与程序输出保持一致）。")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Solve 1D multilayer slab waveguide modes.")
    parser.add_argument("--config", required=True, help="params.json path")
    parser.add_argument("--output", default=None, help="result.json output path")
    args = parser.parse_args()

    config = load_config(args.config)
    modes_by_pol = {}
    for tm, name in ((False, "TE0"), (True, "TM0")):
        roots, _ = solve_modes(config, tm=tm)
        modes_by_pol[name] = roots
    validate_result(modes_by_pol)

    dispersion = []
    base = float(config["lambda0_um"])
    for dlambda in (-0.05, -0.03, -0.01, 0.01, 0.03, 0.05):
        cfg = dict(config)
        cfg["lambda0_um"] = base + dlambda
        roots, _ = solve_modes(cfg, tm=True)
        dispersion.append(
            {"lambda0": round(base + dlambda, 2), "n_eff_tm0": round(float(roots[0]), 4)}
        )

    result = build_result(config, modes_by_pol, dispersion)
    output = args.output
    if output:
        write_result(result, output)
        md_path = os.path.join(os.path.dirname(os.path.abspath(output)), "results.md")
        with open(md_path, "w", encoding="utf-8") as handle:
            handle.write(render_markdown(result))
        print(f"wrote {output}")
        print(f"wrote {md_path}")
    print(json.dumps(result, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
